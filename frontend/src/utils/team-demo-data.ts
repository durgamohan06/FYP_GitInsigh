export function getDemoTeamAnalytics(repoFullName = "gitinsight/intelligence-engine"): TeamAnalyticsData {
  return {
    repository: {
      fullName: repoFullName,
      name: repoFullName.split("/")[1] || repoFullName,
      url: `https://github.com/${repoFullName}`,
      pushedAt: new Date().toISOString(),
      updatedAt: new Date().toISOString(),
    },
    overview: {
      developers: DEMO_DEVELOPERS.length,
      commits: DEMO_DEVELOPERS.reduce((s, d) => s + d.commits, 0),
      pullRequests: DEMO_DEVELOPERS.reduce((s, d) => s + d.pullRequests, 0),
      issues: DEMO_DEVELOPERS.reduce((s, d) => s + d.issues, 0),
      reviews: DEMO_DEVELOPERS.reduce((s, d) => s + d.reviews, 0),
      averageScore: Math.round(
        DEMO_DEVELOPERS.reduce((s, d) => s + d.score, 0) / DEMO_DEVELOPERS.length,
      ),
    },
    developers: DEMO_DEVELOPERS,
    contributionData: {
      commits: DEMO_DEVELOPERS.map((d) => ({ developer: d.username, value: d.commits })),
      pullRequests: DEMO_DEVELOPERS.map((d) => ({ developer: d.username, value: d.pullRequests })),
      issues: DEMO_DEVELOPERS.map((d) => ({ developer: d.username, value: d.issues })),
      reviews: DEMO_DEVELOPERS.map((d) => ({ developer: d.username, value: d.reviews })),
      codeChanges: DEMO_DEVELOPERS.map((d) => ({ developer: d.username, value: d.codeChanges })),
    },
    issueDistribution: [],
    timeline: [],
  };
}
